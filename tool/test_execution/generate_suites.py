"""Keep normal flutter test discovery small without hiding new test files."""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TEST = ROOT / "test"
HEADER = "// Generated by tool/test_execution/generate_suites.py.\n"

# Keep pure HTTP and widget registrations in separate processes and balance
# their modules/shards, without restoring one process for every source file.
PARTITIONS = {"unit": 4, "widgets": 12}
SHARDED = {
    "aggregation/presentation_cases.dart": 3,
    "aggregation/playback_runtime_cases.dart": 3,
    "mobile/phone_pages_cases.dart": 3,
    "mobile/mobile_flow_cases.dart": 4,
    "mobile/phone_player_cases.dart": 4,
    "tv/tv_detail_cases.dart": 2,
    "tv/tv_lan_pair_cases.dart": 3,
    "library/source_detail_route_cases.dart": 3,
    "catalog/item_detail_cases.dart": 3,
    "player/playback_http_proxy_cases.dart": 4,
    "player/rillight_video_backend_cases.dart": 3,
    "player/response_read_ahead_cases.dart": 3,
    "player/cache/cache_contract_cases.dart": 3,
}
ISOLATED = {"app/desktop_scroll_pages_cases.dart": "desktop_scroll"}
# Relative costs from the Windows baseline; large socket/disk fixtures and the
# real KDF cost much more than similarly sized in-memory assertion modules.
WEIGHTS = {
    "player/playback_http_proxy_cases.dart": 2000,
    "player/rillight_video_backend_cases.dart": 1200,
    "player/cache/cache_contract_cases.dart": 700,
    "player/response_read_ahead_cases.dart": 1000,
    "aggregation/access_boundary_cases.dart": 500,
    "player/player_process_control_cases.dart": 400,
}



def group_for(path, source):
    if "testWidgets(" not in source and "Binding.ensureInitialized(" not in source:
        # Registering testWidgets installs Flutter's HTTP mock for the entire
        # process. Keep real socket/HTTP tests in a separate test process.
        return "unit"
    return "widgets"


def generated_files():
    modules = sorted(p.relative_to(TEST).as_posix() for p in TEST.rglob("*_cases.dart"))
    groups = {name: [] for name in PARTITIONS}
    for module in modules:
        if module in ISOLATED:
            continue
        source = (TEST / module).read_text(encoding="utf-8")
        paths = [f"{module}#{part}" for part in range(SHARDED[module])] if module in SHARDED else [module]
        groups[group_for(module, source)].extend(paths)
    result = {}
    balanced = {}
    for name, paths in groups.items():
        bins = [[] for _ in range(PARTITIONS[name])]
        weights = [0] * len(bins)
        def weight(module):
            base = module.split("#")[0]
            source = (TEST / base).read_text(encoding="utf-8")
            estimate = WEIGHTS.get(base, max(1, source.count("testWidgets(") * 8 + source.count("test(")))
            return estimate / SHARDED.get(base, 1)
        for module in sorted(paths, key=lambda m: (-weight(m), m)):
            index = min(range(len(bins)), key=lambda i: (weights[i], i))
            bins[index].append(module)
            weights[index] += weight(module)
        for index, paths in enumerate(bins):
            if paths:
                balanced[f"{name}_{index + 1}"] = sorted(paths)
    groups = balanced
    groups.update({name: [module] for module, name in ISOLATED.items()})
    shared = [HEADER.rstrip()]
    shared += [f"import '../{path}' as case{i};" for i, path in enumerate(modules)]
    shared += ["", "// Import every module once; registering one group calls only its main().",
               "// Importing widget modules alone does not install Flutter's HTTP mock.",
               "final caseEntrypoints = <String, void Function()>{"]
    shared += [f"  '{path}': case{i}.main," for i, path in enumerate(modules)]
    for module, parts in SHARDED.items():
        index = modules.index(module)
        shared += [f"  '{module}#{part}': () => case{index}.mainShard({part}, {parts})," for part in range(parts)]
    shared += ["};", ""]
    result[TEST / "suites" / "modules.dart"] = "\n".join(shared)
    for name, paths in groups.items():
        lines = [HEADER.rstrip(), "import 'package:flutter_test/flutter_test.dart';", ""]
        lines += ["import '../helpers/suite.dart';", "import 'modules.dart';", "", "void main() {", "  verifySuiteManifest();"]
        for path in paths:
            base, _, part = path.partition("#")
            label = base.removesuffix("_cases.dart") + "_test.dart"
            if part:
                label += f" [part {int(part) + 1}]"
            single = f"  group('{label}', caseEntrypoints['{path}']!);"
            if len(single) <= 80:
                lines.append(single)
            else:
                lines += ["  group(", f"    '{label}',", f"    caseEntrypoints['{path}']!,", "  );"]
        lines += ["}", ""]
        result[TEST / "suites" / f"{name}_test.dart"] = "\n".join(lines)
    manifest = HEADER + "const caseModules = <String>[\n"
    manifest += "".join(f"  '{path}',\n" for path in modules)
    result[TEST / "helpers" / "suite_manifest.dart"] = manifest + "];\n"
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    expected = generated_files()
    for path in (TEST / "suites").glob("*_test.dart"):
        if path not in expected and path.read_text(encoding="utf-8").startswith(HEADER):
            if args.check:
                stale.append(path.relative_to(ROOT).as_posix())
            else:
                assert path.resolve().parent == (TEST / "suites").resolve()
                path.unlink()
    for path, source in expected.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != source:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(source, encoding="utf-8", newline="\n")
    if stale:
        parser.exit(1, "Run python tool/test_execution/generate_suites.py: " + ", ".join(stale) + "\n")


if __name__ == "__main__":
    main()
